const norm = (s: string) => s.toLowerCase().normalize('NFD').replace(/\p{Diacritic}/gu, '');

export function guessIcon(name: string) {
  const n = norm(name);
  return RULES.find(([re]) => re.test(n))?.[1] ?? 'libro';
}

export function iconKey(m: { name: string; icono?: string }) {
  return m.icono && ICONS[m.icono] ? m.icono : guessIcon(m.name);
}
